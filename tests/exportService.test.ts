import { describe, expect, it } from 'bun:test';
import { exportService } from '../src/services/exportService';
import { Window } from 'happy-dom';

describe('ExportService SVG Purge Routine', () => {
  it('purges selection rings, ghost lines, distortion badges, and anchor pins from exported SVG', () => {
    const window = new Window();
    const document = window.document;

    const div = document.createElement('div');
    div.innerHTML = `
      <svg viewBox="0 0 500 500">
        <circle id="art-node" cx="50" cy="50" r="10" fill="#e63946" />
        <g class="selection-ring" data-editor-ui="true"><circle r="14" /></g>
        <g class="ghost-trace" data-editor-ui="true"><line x1="50" y1="50" x2="30" y2="30" /></g>
        <g class="distortion-badge" data-editor-ui="true"><text>Δ +35%</text></g>
        <circle class="anchor-pin" cx="55" cy="45" r="3" />
        <g class="bezier-handle"><circle r="4" /></g>
      </svg>
    `;

    const svgElement = div.querySelector('svg') as unknown as SVGSVGElement;
    expect(svgElement).toBeDefined();

    // Polyfill XMLSerializer in happy-dom if needed
    if (typeof (globalThis as any).XMLSerializer === 'undefined') {
      (globalThis as any).XMLSerializer = class {
        serializeToString(node: any) {
          return node.outerHTML || node.innerHTML;
        }
      };
    }

    const purgedXml = exportService.cleanAndPurgeSVG(svgElement);

    expect(purgedXml).toContain('Generated by Cinnamon');
    expect(purgedXml).toContain('xmlns="http://www.w3.org/2000/svg"');
    expect(purgedXml).toContain('art-node');

    // Ensure all editor gizmos were purged
    expect(purgedXml).not.toContain('selection-ring');
    expect(purgedXml).not.toContain('ghost-trace');
    expect(purgedXml).not.toContain('distortion-badge');
    expect(purgedXml).not.toContain('anchor-pin');
    expect(purgedXml).not.toContain('bezier-handle');
  });
});
