import { save } from '@tauri-apps/plugin-dialog';
import { writeTextFile } from '@tauri-apps/plugin-fs';

export class ExportService {
  /**
   * Clones active SVG tree and purges UI gizmos, selection boxes, handles, and ghost lines
   */
  public cleanAndPurgeSVG(originalSvg: SVGSVGElement): string {
    const clone = originalSvg.cloneNode(true) as SVGSVGElement;

    // Selector targeting all editor UI gizmos
    const purgeSelectors = [
      '.editor-gizmo',
      '.selection-box',
      '.selection-ring',
      '.ghost-trace',
      '.ghost-node',
      '.anchor-pin',
      '.distortion-badge',
      '.bezier-handle',
      '.bezier-line',
      '.lasso-preview',
      '[data-editor-ui="true"]',
    ];

    purgeSelectors.forEach((selector) => {
      const elements = clone.querySelectorAll(selector);
      elements.forEach((el) => el.remove());
    });

    // Remove interactive pointer styles and cursors
    clone.removeAttribute('style');
    clone.style.backgroundColor = 'transparent';
    clone.style.fontFamily = '-apple-system, BlinkMacSystemFont, "SF Pro Text", "Helvetica Neue", sans-serif';

    // Ensure valid standalone SVG namespaces and dimensions
    const viewBox = originalSvg.getAttribute('viewBox') || '0 0 960 640';
    clone.setAttribute('xmlns', 'http://www.w3.org/2000/svg');
    clone.setAttribute('xmlns:xlink', 'http://www.w3.org/1999/xlink');
    clone.setAttribute('version', '1.1');
    clone.setAttribute('viewBox', viewBox);

    const serializer = new XMLSerializer();
    const rawXml = serializer.serializeToString(clone);

    const header = `<!-- Generated by Nectarine (macOS Data & Vector Art Atelier) -->\n<!-- Exported on: ${new Date().toISOString()} -->\n`;
    return header + rawXml;
  }

  /**
   * Saves purified SVG to disk using native Tauri FS dialog with fallback to Web download
   */
  public async exportSVG(
    svgContent: string,
    filename = 'nectarine_ilustracion.svg'
  ): Promise<{ success: boolean; filePath?: string; method: 'tauri' | 'web' }> {
    try {
      // Check if Tauri dialog API is available
      if (typeof window !== 'undefined' && (window as any).__TAURI_INTERNALS__) {
        const filePath = await save({
          filters: [
            {
              name: 'Scalable Vector Graphics (.svg)',
              extensions: ['svg'],
            },
          ],
          defaultPath: filename,
        });

        if (filePath) {
          await writeTextFile(filePath, svgContent);
          return { success: true, filePath, method: 'tauri' };
        }
        return { success: false, method: 'tauri' };
      }
    } catch (err) {
      console.warn('Tauri native FS save not available or failed, falling back to web download:', err);
    }

    // Web Fallback: download via anchor tag
    const blob = new Blob([svgContent], { type: 'image/svg+xml;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const anchor = document.createElement('a');
    anchor.href = url;
    anchor.download = filename;
    document.body.appendChild(anchor);
    anchor.click();
    document.body.removeChild(anchor);
    URL.revokeObjectURL(url);

    return { success: true, filePath: filename, method: 'web' };
  }

  /**
   * Copies purified SVG directly to system clipboard for instant 1-click paste into Figma or Adobe Illustrator
   */
  public async copyToClipboard(
    svgContent: string
  ): Promise<{ success: boolean; message: string }> {
    try {
      if (typeof navigator !== 'undefined' && navigator.clipboard) {
        // Try writing rich SVG MIME payload for Figma
        try {
          const textBlob = new Blob([svgContent], { type: 'text/plain' });
          const svgBlob = new Blob([svgContent], { type: 'image/svg+xml' });
          await navigator.clipboard.write([
            new ClipboardItem({
              'text/plain': textBlob,
              'image/svg+xml': svgBlob,
            }),
          ]);
          return {
            success: true,
            message: '¡Vector copiado! Pégalo con ⌘V en Figma o Adobe Illustrator',
          };
        } catch {
          // Standard text copy fallback (Figma & Illustrator also parse plain text SVG)
          await navigator.clipboard.writeText(svgContent);
          return {
            success: true,
            message: '¡Vector copiado! Pégalo con ⌘V en Figma o Adobe Illustrator',
          };
        }
      }
      return { success: false, message: 'El portapapeles del sistema no está accesible' };
    } catch (err: any) {
      return { success: false, message: `Error al copiar al portapapeles: ${err?.message || err}` };
    }
  }
}

export const exportService = new ExportService();
